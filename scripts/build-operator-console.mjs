import { readFile, writeFile } from "node:fs/promises";

import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const outputUrl = new URL("src/operator-console-client.generated.ts", root);
const check = process.argv.includes("--check");

const result = await build({
  entryPoints: [new URL("src/operator-console-client.tsx", root).pathname],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  minify: true,
  legalComments: "none",
  write: false,
  jsx: "automatic",
  jsxImportSource: "hono/jsx/dom",
});

const bundled = result.outputFiles?.[0]?.text;
if (!bundled) throw new Error("The operator console client bundle was empty.");

const generated = `// Generated by scripts/build-operator-console.mjs. Do not edit.\n` +
  `export const OPERATOR_CONSOLE_COMPONENTS_JS = ${JSON.stringify(bundled)};\n`;

if (check) {
  const existing = await readFile(outputUrl, "utf8").catch(() => "");
  if (existing !== generated) {
    throw new Error(
      "The operator console browser bundle is stale. Run npm run generate:console.",
    );
  }
} else {
  await writeFile(outputUrl, generated, "utf8");
}
